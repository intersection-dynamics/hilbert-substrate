def transmission_hamiltonian(d_B, variant='standard'):
    """
    Hamiltonian for site_a ⊗ bond ⊗ site_b transmission.
    Returns H acting on C^2 ⊗ C^{d_B} ⊗ C^2.
    """
    sx = np.array([[0, 1], [1, 0]], dtype=complex)
    sy = np.array([[0, -1j], [1j, 0]], dtype=complex)
    sz = np.array([[1, 0], [0, -1]], dtype=complex)
    I2 = np.eye(2, dtype=complex)
    IB = np.eye(d_B, dtype=complex)
    
    # Bond operators
    if d_B == 2:
        Bx, By, Bz = sx.copy(), sy.copy(), sz.copy()
    else:
        # Generalized spin-(d_B-1)/2 operators
        s = (d_B - 1) / 2.0
        Bx = np.zeros((d_B, d_B), dtype=complex)
        By = np.zeros((d_B, d_B), dtype=complex)
        Bz = np.zeros((d_B, d_B), dtype=complex)
        for m_idx in range(d_B):
            m = s - m_idx
            if m_idx + 1 < d_B:
                mp = m - 1
                coeff = np.sqrt(s*(s+1) - m*mp) * 0.5
                Bx[m_idx, m_idx+1] = coeff
                Bx[m_idx+1, m_idx] = coeff
                By[m_idx, m_idx+1] = -1j * coeff
                By[m_idx+1, m_idx] = 1j * coeff
            Bz[m_idx, m_idx] = m
    
    if variant == 'standard':
        # σ_x ⊗ B_x ⊗ σ_x + σ_z ⊗ B_z ⊗ σ_z + 0.3 σ_y ⊗ I_B ⊗ σ_y
        H = (np.kron(np.kron(sx, Bx), sx) +
             np.kron(np.kron(sz, Bz), sz) +
             0.3 * np.kron(np.kron(sy, IB), sy))
    elif variant == 'full':
        # All three channels coupled: σ_α ⊗ B_α ⊗ σ_α for α=x,y,z
        H = (np.kron(np.kron(sx, Bx), sx) +
             np.kron(np.kron(sy, By), sy) +
             np.kron(np.kron(sz, Bz), sz))
    elif variant == 'random':
        # Random Hermitian coupling
        d_full = 2 * d_B * 2
        H = np.random.randn(d_full, d_full) + 1j * np.random.randn(d_full, d_full)
        H = (H + H.conj().T) / 2.0
    
    return H


def extract_kraus_operators(U_full, d_B, psi_a, psi_b):
    """
    Given a unitary U on C^2 ⊗ C^{d_B} ⊗ C^2 and input site states
    |ψ_a⟩, |ψ_b⟩, compute the Kraus operators for the induced
    channel on the bond.
    
    K_{mn} = (⟨m_a| ⊗ I_B ⊗ ⟨n_b|) U (|ψ_a⟩ ⊗ I_B ⊗ |ψ_b⟩)
    
    Each K_{mn} is a d_B × d_B matrix.
    Returns list of Kraus operators.
    """
    d_full = 2 * d_B * 2
    
    # Reshape U as tensor: U[a_out, b_out, b_in, a_in, b_out2, b_in2]
    # Actually, U acts on (site_a, bond, site_b) → (site_a, bond, site_b)
    # U has shape (2*d_B*2, 2*d_B*2)
    # Index: i = a*d_B*2 + b*2 + c where a=site_a, b=bond, c=site_b
    
    kraus_ops = []
    
    # Build the "input embedding": |ψ_a⟩ ⊗ I_B ⊗ |ψ_b⟩
    # This maps |φ_bond⟩ → |ψ_a⟩ ⊗ |φ_bond⟩ ⊗ |ψ_b⟩
    # As a matrix: (2*d_B*2) × d_B
    embed = np.zeros((d_full, d_B), dtype=complex)
    for b in range(d_B):
        for a in range(2):
            for c in range(2):
                row = a * (d_B * 2) + b * 2 + c
                embed[row, b] = psi_a[a] * psi_b[c]
    
    # Apply U: U @ embed gives (2*d_B*2) × d_B
    U_embed = U_full @ embed
    
    # Extract Kraus operators by projecting output sites
    for m in range(2):      # output site_a
        for n in range(2):  # output site_b
            K = np.zeros((d_B, d_B), dtype=complex)
            for b_out in range(d_B):
                row = m * (d_B * 2) + b_out * 2 + n
                for b_in in range(d_B):
                    K[b_out, b_in] = U_embed[row, b_in]
            kraus_ops.append(K)
    
    return kraus_ops


def effective_bond_unitary(U_full, d_B, psi_a, psi_b):
    """
    When both sites start in known pure states, the dominant
    Kraus operator (the one with largest norm) approximates
    the effective unitary on the bond.
    
    For weak coupling, this is close to a unitary.
    Returns the dominant Kraus operator (normalized).
    """
    kraus = extract_kraus_operators(U_full, d_B, psi_a, psi_b)
    
    # Find the one with largest Frobenius norm
    norms = [np.linalg.norm(K, 'fro') for K in kraus]
    dominant_idx = np.argmax(norms)
    K_dom = kraus[dominant_idx]
    
    # Also compute the full channel superoperator for completeness
    # ρ → Σ K_i ρ K_i†
    return K_dom, kraus


def extract_generators_infinitesimal(d_B, H_transmission, n_site_samples=50):
    """
    Extract Lie algebra generators by taking infinitesimal transmissions.
    
    At small coupling ε:
    U ≈ I - iεH
    K_{mn} ≈ δ_{m,ψ_a} δ_{n,ψ_b} I_B - iε (⟨m|⊗I⊗⟨n|) H (|ψ_a⟩⊗I⊗|ψ_b⟩)
    
    The first-order bond operator (removing identity) is the generator.
    """
    d_full = 2 * d_B * 2
    eps = 1e-4
    U = expm(-1j * eps * H_transmission)
    
    generators = []
    
    for _ in range(n_site_samples):
        # Random site states (Haar random on qubit)
        psi_a = np.random.randn(2) + 1j * np.random.randn(2)
        psi_a /= np.linalg.norm(psi_a)
        psi_b = np.random.randn(2) + 1j * np.random.randn(2)
        psi_b /= np.linalg.norm(psi_b)
        
        kraus = extract_kraus_operators(U, d_B, psi_a, psi_b)
        
        # Each Kraus operator K ≈ c_{mn} I + ε G_{mn}
        # Extract the first-order part
        for K in kraus:
            # Remove identity component
            trace_part = np.trace(K) / d_B
            G = (K - trace_part * np.eye(d_B)) / eps
            
            if np.linalg.norm(G) > 1e-8:
                # Decompose into Hermitian and anti-Hermitian parts
                G_herm = (G + G.conj().T) / 2.0
                G_anti = (G - G.conj().T) / (2.0j)
                
                if np.linalg.norm(G_herm) > 1e-8:
                    generators.append(G_herm / np.linalg.norm(G_herm))
                if np.linalg.norm(G_anti) > 1e-8:
                    generators.append(G_anti / np.linalg.norm(G_anti))
    
    return generators


def extract_generators_finite(d_B, H_transmission, coupling_range, n_site_samples=100):
    """
    Extract generators from finite-strength transmissions.
    Compute effective bond unitaries, take logarithms.
    """
    d_full = 2 * d_B * 2
    generators = []
    
    for coupling in coupling_range:
        U = expm(-1j * coupling * H_transmission)
        
        for _ in range(n_site_samples):
            psi_a = np.random.randn(2) + 1j * np.random.randn(2)
            psi_a /= np.linalg.norm(psi_a)
            psi_b = np.random.randn(2) + 1j * np.random.randn(2)
            psi_b /= np.linalg.norm(psi_b)
            
            K_dom, kraus = effective_bond_unitary(U, d_B, psi_a, psi_b)
            
            # For the dominant Kraus operator, extract the generator
            # K ≈ c * exp(iG) where G is Hermitian
            if np.linalg.norm(K_dom) > 0.1:
                # Normalize to make it closer to unitary
                K_norm = K_dom / np.linalg.norm(K_dom) * np.sqrt(d_B)
                
                # Polar decomposition to extract unitary part
                U_part, S, Vh = np.linalg.svd(K_dom)
                U_eff = U_part @ Vh
                
                # Extract generator via logarithm
                try:
                    log_U = logm(U_eff)
                    G = 1j * log_U  # U = exp(-iG), so G = i*log(U)
                    G_herm = (G + G.conj().T) / 2.0
                    G_traceless = G_herm - np.trace(G_herm)/d_B * np.eye(d_B)
                    
                    if np.linalg.norm(G_traceless) > 1e-6:
                        generators.append(G_traceless / np.linalg.norm(G_traceless))
                except:
                    pass
    
    return generators


