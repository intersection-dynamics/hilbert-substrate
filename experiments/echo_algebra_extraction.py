"""
Echo Algebra Extraction (Task A1/A2)
====================================

Goal: Determine the Lie algebra generated by echo operations on
a single bond. If d_B=2 gives su(2) and d_B=3 gives su(3),
this is strong evidence that gauge groups emerge from bond dimension.

Method:
1. A transmission U acts on (site_a ⊗ bond ⊗ site_b)
2. For fixed input site states |ψ_a⟩, |ψ_b⟩, tracing over output
   sites yields Kraus operators K_{mn} on the bond
3. The *algebra* generated by all such K operators (for all
   possible site inputs and transmission types) is the echo algebra
4. Extract generators, compute structure constants, identify the algebra

Key insight: We don't need the full channel. We need the GROUP of
effective bond transformations. At infinitesimal coupling, each
transmission generates a Hermitian operator on the bond — these
are the Lie algebra generators.
"""

