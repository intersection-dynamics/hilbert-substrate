def find_independent_generators(generators, d_B, tol=1e-6):
    """
    From a collection of d_B × d_B traceless Hermitian matrices,
    find a linearly independent basis using SVD.
    """
    if not generators:
        return [], np.array([])
    
    # Flatten each generator to a real vector
    # A traceless Hermitian d×d matrix has d²-1 real parameters
    n_params = d_B * d_B  # use full matrix for safety
    
    vectors = []
    for G in generators:
        # Ensure traceless Hermitian
        G = (G + G.conj().T) / 2.0
        G -= np.trace(G) / d_B * np.eye(d_B)
        
        # Flatten: real and imaginary parts of upper triangle + diagonal
        v = []
        for i in range(d_B):
            v.append(G[i, i].real)  # diagonal is real for Hermitian
        for i in range(d_B):
            for j in range(i+1, d_B):
                v.append(G[i, j].real)
                v.append(G[i, j].imag)
        vectors.append(v)
    
    V = np.array(vectors)
    
    # SVD to find rank
    U_svd, S, Vh = np.linalg.svd(V, full_matrices=False)
    
    # Count significant singular values
    n_indep = np.sum(S > tol * S[0])
    
    # Extract independent generators from right singular vectors
    basis_vectors = Vh[:n_indep]
    
    # Reconstruct matrices from vectors
    basis_generators = []
    for v in basis_vectors:
        G = np.zeros((d_B, d_B), dtype=complex)
        idx = 0
        for i in range(d_B):
            G[i, i] = v[idx]
            idx += 1
        for i in range(d_B):
            for j in range(i+1, d_B):
                G[i, j] = v[idx] + 1j * v[idx+1]
                G[j, i] = v[idx] - 1j * v[idx+1]
                idx += 2
        
        # Normalize
        G /= np.linalg.norm(G)
        basis_generators.append(G)
    
    return basis_generators, S


def compute_structure_constants(basis, d_B):
    """
    Compute structure constants f_{abc} defined by:
    [T_a, T_b] = i Σ_c f_{abc} T_c
    
    where {T_a} is the orthonormal basis of generators.
    """
    n = len(basis)
    
    # First orthonormalize using Hilbert-Schmidt inner product
    # ⟨A, B⟩ = Tr(A† B) / normalization
    ortho_basis = []
    for i, G in enumerate(basis):
        v = G.copy()
        for prev in ortho_basis:
            overlap = np.trace(prev.conj().T @ v).real
            v -= overlap * prev
        norm = np.sqrt(np.trace(v.conj().T @ v).real)
        if norm > 1e-10:
            ortho_basis.append(v / norm)
    
    n = len(ortho_basis)
    f = np.zeros((n, n, n))
    
    for a in range(n):
        for b in range(n):
            comm = ortho_basis[a] @ ortho_basis[b] - ortho_basis[b] @ ortho_basis[a]
            # [T_a, T_b] = i Σ_c f_{abc} T_c
            # So f_{abc} = -i Tr(T_c† [T_a, T_b]) / Tr(T_c† T_c)
            for c in range(n):
                f[a, b, c] = (-1j * np.trace(ortho_basis[c].conj().T @ comm)).real
    
    return f, ortho_basis


def check_jacobi_identity(f, n_generators):
    """Verify f satisfies the Jacobi identity."""
    max_violation = 0
    for a in range(n_generators):
        for b in range(n_generators):
            for c in range(n_generators):
                # Σ_d (f_{abd} f_{dce} + f_{bcd} f_{dae} + f_{cad} f_{dbe}) = 0
                for e in range(n_generators):
                    val = 0
                    for d in range(n_generators):
                        val += f[a,b,d]*f[d,c,e] + f[b,c,d]*f[d,a,e] + f[c,a,d]*f[d,b,e]
                    max_violation = max(max_violation, abs(val))
    return max_violation


def identify_algebra(f, n_generators, ortho_basis):
    """
    Identify the Lie algebra from its structure constants.
    
    Key signatures:
    - su(2): 3 generators, f_{abc} = ε_{abc} (Levi-Civita)
    - su(3): 8 generators, specific f values
    - u(1): 1 generator, all f = 0
    - su(2) ⊕ u(1): 4 generators, block structure
    """
    print(f"\n{'='*60}")
    print(f"ALGEBRA IDENTIFICATION")
    print(f"{'='*60}")
    print(f"Number of independent generators: {n_generators}")
    print(f"Expected for su(n): n²-1  →  su(2)=3, su(3)=8, su(4)=15")
    
    # Compute the Killing form: K_{ab} = Σ_{c,d} f_{acd} f_{bdc}
    K = np.zeros((n_generators, n_generators))
    for a in range(n_generators):
        for b in range(n_generators):
            for c in range(n_generators):
                for d in range(n_generators):
                    K[a, b] += f[a, c, d] * f[b, d, c]
    
    print(f"\nKilling form eigenvalues: {np.sort(np.linalg.eigvalsh(K))}")
    
    # For su(n), K_{ab} = 2n δ_{ab} (with standard normalization)
    # Check if K is proportional to identity
    K_trace = np.trace(K)
    K_normalized = K / (K_trace / n_generators) if abs(K_trace) > 1e-10 else K
    
    identity_dev = np.linalg.norm(K_normalized - np.eye(n_generators))
    print(f"Killing form ∝ identity? Deviation: {identity_dev:.6f}")
    
    if identity_dev < 0.1:
        # Simple algebra! K ∝ I means it's simple (or abelian)
        kappa = K_trace / n_generators
        print(f"Killing form coefficient κ = {kappa:.4f}")
        
        if n_generators == 3:
            # Check against su(2)
            print(f"\n→ 3 generators with simple Killing form")
            print(f"  Testing su(2) identification...")
            
            # For su(2) with [T_a, T_b] = i ε_{abc} T_c:
            # f_{abc} = ε_{abc}, K_{ab} = -2δ_{ab}
            check_su2(f)
            
        elif n_generators == 8:
            print(f"\n→ 8 generators with simple Killing form")
            print(f"  Testing su(3) identification...")
            check_su3(f)
    else:
        # Check for semi-simple decomposition
        print(f"\nKilling form is NOT proportional to identity.")
        print(f"Checking for direct sum decomposition...")
        
        # Eigendecompose K to find blocks
        evals, evecs = np.linalg.eigh(K)
        print(f"Killing eigenvalues: {evals}")
    
    # Jacobi identity check
    jacobi_violation = check_jacobi_identity(f, n_generators)
    print(f"\nJacobi identity max violation: {jacobi_violation:.2e}")
    
    # Compute Casimir operator
    if abs(K_trace) > 1e-10:
        K_inv = np.linalg.inv(K) if abs(np.linalg.det(K)) > 1e-10 else np.linalg.pinv(K)
        print(f"\nComputing quadratic Casimir...")
        d_B = ortho_basis[0].shape[0]
        C2 = np.zeros((d_B, d_B), dtype=complex)
        for a in range(n_generators):
            for b in range(n_generators):
                C2 += K_inv[a, b] * ortho_basis[a] @ ortho_basis[b]
        
        C2_evals = np.linalg.eigvalsh(C2)
        print(f"Casimir eigenvalues: {C2_evals}")
        if np.std(C2_evals) / (np.mean(np.abs(C2_evals)) + 1e-10) < 0.01:
            print(f"→ Casimir is proportional to identity (irreducible rep!)")
    
    return K


def check_su2(f):
    """Check if structure constants match su(2) = {f_{abc} = ε_{abc}}."""
    # The Levi-Civita tensor
    eps = np.zeros((3, 3, 3))
    eps[0, 1, 2] = eps[1, 2, 0] = eps[2, 0, 1] = 1
    eps[0, 2, 1] = eps[2, 1, 0] = eps[1, 0, 2] = -1
    
    # f might differ by an overall sign and ordering.
    # Find the best permutation and sign.
    
    # Compute the totally antisymmetric part of f
    f_anti = np.zeros((3, 3, 3))
    for a in range(3):
        for b in range(3):
            for c in range(3):
                f_anti[a, b, c] = (f[a,b,c] - f[b,a,c] - f[a,c,b] + f[c,a,b] +
                                   f[b,c,a] - f[c,b,a]) / 6.0
    
    # f should already be antisymmetric in first two indices
    # For su(2), f_{abc} = α ε_{abc} for some α
    # Find α by matching
    alpha_estimates = []
    for a in range(3):
        for b in range(3):
            for c in range(3):
                if abs(eps[a, b, c]) > 0.5:
                    alpha_estimates.append(f[a, b, c] / eps[a, b, c])
    
    if alpha_estimates:
        alpha = np.mean(alpha_estimates)
        residual = np.linalg.norm(f - alpha * eps)
        print(f"  Best fit: f_{{abc}} = {alpha:.4f} × ε_{{abc}}")
        print(f"  Residual: {residual:.6f}")
        print(f"  → {'SU(2) CONFIRMED' if residual < 0.1 else 'NOT su(2)'}")
        return alpha, residual
    else:
        print(f"  No nonzero Levi-Civita components found")
        return None, None


