def run_test(d_link, d_site, n_trials=10, seed=42, gauge_tol=1e-6):
    """
    For each trial:
      1. Random su(d_site) embeddings L, R in d_link-dim link
      2. Optimize R for no-signaling: min Σ||[L,R]||²
      3. Measure:
         a) No-signaling cost (should → 0 if achievable)
         b) Algebra dimension of L∪R (should = d_link² if no-forgetting)
         c) Gauge invariance of induced Hamiltonian
    """
    rng = np.random.default_rng(seed)
    T_site = su_generators(d_site)
    T_link = su_generators(d_link)
    n_site_gen = len(T_site)
    n_link_gen = len(T_link)

    I_site = np.eye(d_site, dtype=complex)
    I_link = np.eye(d_link, dtype=complex)

    results = []

    for trial in range(n_trials):
        rng_t = np.random.default_rng(seed + trial * 1000)

        # Embed T_site into d_link (top-left block, then conjugate by random unitary)
        def embed(Ta, d_big):
            M = np.zeros((d_big, d_big), dtype=complex)
            ds = Ta.shape[0]
            M[:ds, :ds] = Ta
            return hermitize(traceless(M))

        T_emb = [embed(Ta, d_link) for Ta in T_site]

        W_L = random_su_element(d_link, rng_t)
        W_R_init = random_su_element(d_link, rng_t)

        L_ops = [W_L @ Te @ W_L.conj().T for Te in T_emb]

        def make_R_ops(theta):
            H_p = sum(t * G for t, G in zip(theta, T_link))
            V = W_R_init @ expm(1j * H_p)
            return [V @ Te @ V.conj().T for Te in T_emb]

        def cost_ns(theta):
            R_ops = make_R_ops(theta)
            total = 0.0
            for a in range(n_site_gen):
                for b in range(n_site_gen):
                    C = comm(L_ops[a], R_ops[b])
                    total += np.sum(np.abs(C) ** 2).real
            return float(total)

        # Optimize no-signaling
        best_cost = cost_ns(np.zeros(n_link_gen))
        best_theta = np.zeros(n_link_gen)

        for restart in range(5):
            if restart == 0:
                t0 = np.zeros(n_link_gen)
            else:
                t0 = rng_t.normal(scale=0.5, size=n_link_gen)
            res = minimize(cost_ns, t0, method='L-BFGS-B',
                           options={'maxiter': 3000, 'ftol': 1e-15, 'gtol': 1e-12})
            if res.fun < best_cost:
                best_cost = res.fun
                best_theta = res.x.copy()

        R_ops_final = make_R_ops(best_theta)
        commuting = best_cost < 1e-8

        # Max [L,R] commutator
        max_comm = 0.0
        for a in range(n_site_gen):
            for b in range(n_site_gen):
                max_comm = max(max_comm, fro(comm(L_ops[a], R_ops_final[b])))

        # NO-FORGETTING: algebra dimension
        all_ops = L_ops + R_ops_final
        alg_dim = algebra_dimension(all_ops, d_link, max_depth=4)
        full_algebra = (alg_dim >= d_link * d_link)
        irreducible = full_algebra

        # Also compute algebra dim of L alone and R alone
        alg_dim_L = algebra_dimension(L_ops, d_link, max_depth=3)
        alg_dim_R = algebra_dimension(R_ops_final, d_link, max_depth=3)

        # GAUGE INVARIANCE check
        D_full = d_site * d_link * d_site
        H_coupling = np.zeros((D_full, D_full), dtype=complex)
        for a in range(n_site_gen):
            H_coupling += kron(T_site[a], L_ops[a], I_site)
            H_coupling += kron(I_site, R_ops_final[a], T_site[a])
        H_coupling = hermitize(H_coupling)

        max_gauss = 0.0
        for a in range(n_site_gen):
            G_L = kron(T_site[a], I_link, I_site) + kron(I_site, L_ops[a], I_site)
            G_R = kron(I_site, I_link, T_site[a]) + kron(I_site, R_ops_final[a], I_site)
            max_gauss = max(max_gauss, fro(comm(H_coupling, G_L)))
            max_gauss = max(max_gauss, fro(comm(H_coupling, G_R)))

        gauge_inv = max_gauss < gauge_tol

        # Casimir eigenvalues (structural diagnostic)
        C_L = sum(La @ La for La in L_ops)
        C_R = sum(Ra @ Ra for Ra in R_ops_final)
        evals_CL = np.sort(np.linalg.eigvalsh(hermitize(C_L).real))
        evals_CR = np.sort(np.linalg.eigvalsh(hermitize(C_R).real))

        def degeneracy_pattern(evals, tol=1e-4):
            groups = []
            current = [evals[0]]
            for e in evals[1:]:
                if abs(e - current[0]) < tol:
                    current.append(e)
                else:
                    groups.append(len(current))
                    current = [e]
            groups.append(len(current))
            return sorted(groups, reverse=True)

        pat_L = degeneracy_pattern(evals_CL)
        pat_R = degeneracy_pattern(evals_CR)

        # Both constraints satisfied?
        both = commuting and irreducible

        r = {
            'trial': trial,
            'ns_cost': float(best_cost),
            'max_comm_LR': float(max_comm),
            'commuting': bool(commuting),
            'alg_dim_joint': int(alg_dim),
            'alg_dim_L': int(alg_dim_L),
            'alg_dim_R': int(alg_dim_R),
            'alg_dim_full': int(d_link * d_link),
            'irreducible': bool(irreducible),
            'both_satisfied': bool(both),
            'max_gauss': float(max_gauss),
            'gauge_invariant': bool(gauge_inv),
            'casimir_L': evals_CL.tolist(),
            'casimir_R': evals_CR.tolist(),
            'degeneracy_L': pat_L,
            'degeneracy_R': pat_R,
        }
        results.append(r)

        # Status string
        flags = []
        if commuting: flags.append("NS")
        if irreducible: flags.append("NF")
        if gauge_inv: flags.append("GAUGE")
        status = "+".join(flags) if flags else "NONE"

        print(f"  Trial {trial+1:>2}/{n_trials}: "
              f"ns_cost={best_cost:.2e}  "
              f"max[L,R]={max_comm:.2e}  "
              f"alg={alg_dim}/{d_link**2}  "
              f"gauss={max_gauss:.2e}  "
              f"deg_L={pat_L}  "
              f"[{status}]")

    return results


