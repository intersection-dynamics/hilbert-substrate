def hs_norm(A):
    return float(np.sqrt(max(np.trace(A.conj().T @ A).real, 0.0)))

def fro(A):
    return float(np.linalg.norm(A, 'fro'))

def comm(A, B):
    return A @ B - B @ A

def hermitize(A):
    return (A + A.conj().T) / 2.0

def traceless(A):
    d = A.shape[0]
    return A - (np.trace(A) / d) * np.eye(d, dtype=complex)

def kron(*ops):
    out = ops[0]
    for X in ops[1:]:
        out = np.kron(out, X)
    return out


def su_generators(d):
    gens = []
    for i in range(d):
        for j in range(i + 1, d):
            S = np.zeros((d, d), dtype=complex)
            S[i, j] = 1.0; S[j, i] = 1.0
            gens.append(S)
            A = np.zeros((d, d), dtype=complex)
            A[i, j] = -1j; A[j, i] = 1j
            gens.append(A)
    for k in range(1, d):
        D = np.zeros((d, d), dtype=complex)
        for i in range(k):
            D[i, i] = 1.0
        D[k, k] = -float(k)
        D *= math.sqrt(2.0 / (k * (k + 1.0)))
        gens.append(D)
    out = []
    for G in gens:
        H = hermitize(traceless(G))
        n = hs_norm(H)
        if n > 1e-12:
            out.append(H / n)
    return out


def random_su_element(d, rng):
    gens = su_generators(d)
    coeffs = rng.normal(size=len(gens))
    H = sum(c * G for c, G in zip(coeffs, gens))
    return expm(1j * H)


# ======================================================================
# Algebra dimension computation (Burnside diagnostic)
# ======================================================================

def algebra_dimension(ops, d, max_depth=4):
    """
    Compute dimension of the matrix algebra generated by a set of operators.

    Uses iterated products and commutators to build the algebra, then counts
    linearly independent elements via SVD of the vectorized basis.

    For irreducible action on C^d, this should be d² (full matrix algebra).
    For reducible action, it will be < d².

    Parameters
    ----------
    ops : list of d×d complex matrices (the generators)
    d : dimension of the space they act on
    max_depth : maximum number of multiplication rounds

    Returns
    -------
    dim : int, dimension of generated algebra
    """
    # Vectorize: d×d matrix → d² vector
    def vec(M):
        return M.reshape(-1)

    # Start with identity + all generators
    basis_vecs = [vec(np.eye(d, dtype=complex))]
    for O in ops:
        basis_vecs.append(vec(O))

    def current_dim(vecs):
        if len(vecs) == 0:
            return 0
        M = np.array(vecs)
        svals = np.linalg.svd(M, compute_uv=False)
        return int(np.sum(svals > 1e-10))

    # Iteratively add products until saturated
    current_ops = list(ops)
    for depth in range(max_depth):
        new_vecs = []
        for A in current_ops:
            for B in ops:
                # Product
                AB = A @ B
                new_vecs.append(vec(AB))
                # Commutator
                C = A @ B - B @ A
                new_vecs.append(vec(C))

        # Add to basis
        old_dim = current_dim(basis_vecs)
        basis_vecs.extend(new_vecs)
        new_dim = current_dim(basis_vecs)

        if new_dim == old_dim or new_dim >= d * d:
            break

        # Update current_ops to include newly found independent elements
        # (use a representative subset to keep computation manageable)
        M = np.array(basis_vecs)
        U, S, Vt = np.linalg.svd(M, full_matrices=False)
        n_indep = int(np.sum(S > 1e-10))
        # Reconstruct independent operators
        current_ops = []
        for i in range(min(n_indep, d * d)):
            mat = Vt[i].reshape(d, d)
            current_ops.append(mat)

    return current_dim(basis_vecs)


